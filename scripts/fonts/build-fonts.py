"""Builds the self-hosted web fonts from the TTF sources in scripts/fonts/source.

Each face is split like Google Fonts does it:
  - a "latin" WOFF2 covering German, English and Turkish (Latin, Latin Extended,
    punctuation, currency, arrows). It is small, preloaded on every page and
    uses font-display: optional, so text is painted in the real font from the
    first frame and never swaps afterwards;
  - an "ext" WOFF2 with everything else (Cyrillic, Greek, Vietnamese). Its
    unicode-range keeps it from downloading unless a page uses those letters.

File names carry a content hash, so /assets/fonts can be cached forever
(next.config.ts). Writes public/assets/fonts/*.woff2, public/assets/css/fonts.css
(mirrored into static-site/assets) and lib/font-preloads.json.

Usage (from the repository root):
    pip install fonttools brotli
    python scripts/fonts/build-fonts.py
"""

import hashlib
import io
import json
import re
import shutil
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "scripts" / "fonts" / "source"
TARGETS = [ROOT / "public" / "assets", ROOT / "static-site" / "assets"]
PRELOADS = ROOT / "lib" / "font-preloads.json"

FAMILIES = {"Manrope": "manrope", "DMMono": "dm-mono"}
CSS_NAMES = {"Manrope": "Manrope", "DMMono": "DM Mono"}

# Latin + Latin Extended + what the interface uses around them.
LATIN = [
    (0x0000, 0x024F), (0x0259, 0x0259), (0x02B0, 0x02FF), (0x0300, 0x036F),
    (0x1E00, 0x1EFF), (0x2000, 0x206F), (0x20A0, 0x20CF), (0x2100, 0x214F),
    (0x2190, 0x21FF), (0x2212, 0x2212), (0x2215, 0x2215), (0xFEFF, 0xFEFF), (0xFFFD, 0xFFFD),
]


def in_latin(codepoint: int) -> bool:
    return any(start <= codepoint <= end for start, end in LATIN)


def unicode_range(codepoints: set[int]) -> str:
    spans, start, previous = [], None, None
    for codepoint in sorted(codepoints):
        if start is None:
            start = previous = codepoint
        elif codepoint == previous + 1:
            previous = codepoint
        else:
            spans.append((start, previous))
            start = previous = codepoint
    if start is not None:
        spans.append((start, previous))
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in spans)


def woff2(source: Path, codepoints: set[int]) -> bytes:
    options = subset.Options()
    options.flavor = "woff2"
    options.layout_features = ["*"]
    options.name_IDs = ["*"]
    options.notdef_outline = True
    # Keep the source timestamp so an unchanged font yields the same bytes (and file name) every run.
    font = TTFont(source, recalcTimestamp=False)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    buffer = io.BytesIO()
    font.flavor = "woff2"
    font.save(buffer)
    return buffer.getvalue()


def main() -> None:
    faces, files, preloads = [], {}, []
    for source in sorted(SOURCE.glob("*.ttf")):
        match = re.fullmatch(r"(Manrope|DMMono)-(\d{3})", source.stem)
        if not match:
            raise SystemExit(f"Unexpected source name {source.name}; use <Family>-<weight>.ttf")
        family, weight = match.group(1), int(match.group(2))
        codepoints = set(TTFont(source).getBestCmap())
        latin = {c for c in codepoints if in_latin(c)}
        for part, chars, display in (("latin", latin, "optional"), ("ext", codepoints - latin, "swap")):
            if not chars:
                continue
            data = woff2(source, chars)
            name = f"{FAMILIES[family]}-{weight}-{part}.{hashlib.sha256(data).hexdigest()[:8]}.woff2"
            files[name] = data
            faces.append(
                "@font-face {\n"
                f"  font-family: '{CSS_NAMES[family]}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {weight};\n"
                f"  font-display: {display};\n"
                f"  src: url(/assets/fonts/{name}) format('woff2');\n"
                f"  unicode-range: {unicode_range(chars)};\n"
                "}"
            )
            if part == "latin":
                preloads.append(f"/assets/fonts/{name}")

    css = (
        "/* Generated by scripts/fonts/build-fonts.py; edit the script, not this file.\n"
        "   Latin faces are preloaded (lib/fonts.ts) and use font-display: optional so text never\n"
        "   swaps font after the first paint; other scripts download only when a page uses them. */\n"
        + "\n".join(faces)
        + "\n"
    )
    for target in TARGETS:
        fonts = target / "fonts"
        fonts.mkdir(parents=True, exist_ok=True)
        for stale in list(fonts.glob("*.woff2")) + list(fonts.glob("*.ttf")):
            if stale.name not in files:
                stale.unlink()
        for name, data in files.items():
            (fonts / name).write_bytes(data)
        for licence in SOURCE.glob("*-OFL.txt"):
            shutil.copyfile(licence, fonts / licence.name)
        (target / "css" / "fonts.css").write_text(css, encoding="utf-8", newline="\n")
    PRELOADS.write_text(json.dumps(preloads, indent=2) + "\n", encoding="utf-8", newline="\n")
    total = sum(len(files[Path(p).name]) for p in preloads)
    print(f"{len(files)} files, {len(preloads)} preloaded ({total / 1024:.1f} KB)")


if __name__ == "__main__":
    main()
