#!/usr/bin/env node
/**
 * Regenerates app/panel/_components/panel-icons.ts from the Iconify Lucide set.
 *
 * Only the icons listed in ICONS are bundled, so the panel stays offline and
 * the client bundle stays small. Add a semantic key here (and run this script)
 * when the navigation needs a new icon.
 *
 * Usage: node scripts/generate-panel-icons.mjs
 */
import { createRequire } from "node:module";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { icons, aliases = {} } = require("@iconify-json/lucide/icons.json");

const ICONS = {
  overview: "layout-dashboard",
  inbox: "inbox",
  reviews: "star",
  users: "users",
  products: "package",
  changelog: "scroll-text",
  blog: "newspaper",
  media: "image",
  settings: "settings",
  transfer: "arrow-down-up",
  billing: "credit-card",
  chevronDown: "chevron-down",
  signOut: "log-out",
};

const lines = [
  "// Generated by scripts/generate-panel-icons.mjs — do not edit by hand.",
  "// Icons: Lucide via Iconify (https://iconify.design/icon-sets/lucide/).",
  "",
  "export const PANEL_ICONS = {",
];

for (const [key, name] of Object.entries(ICONS)) {
  const icon = icons[name] ?? icons[aliases[name]?.parent];
  if (!icon) throw new Error(`Lucide icon not found: ${name}`);
  const body = icon.body.replaceAll('stroke-width="2"', 'stroke-width="1.75"');
  lines.push(`  ${key}: {`);
  lines.push(`    body: ${JSON.stringify(body)},`);
  lines.push(`    width: ${icon.width ?? 24},`);
  lines.push(`    height: ${icon.height ?? 24},`);
  lines.push("  },");
}

lines.push("} as const;", "", "export type PanelIconName = keyof typeof PANEL_ICONS;", "");

const target = fileURLToPath(new URL("../app/panel/_components/panel-icons.ts", import.meta.url));
await writeFile(target, lines.join("\n"), "utf8");
console.log(`Wrote ${Object.keys(ICONS).length} icons to ${target}`);
